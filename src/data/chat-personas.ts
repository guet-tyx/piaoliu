  image: string;
  /** 空态问候签名，如「—— 汐 · 星海版限定」 */
  signature: string;
  /**
   * MiMo 预置音色 id（V2.5 中文音色：冰糖/茉莉=女声，苏打/白桦=男声）。
   * 会作为 audio.voice 传给 TTS 请求；voiceDesign=true 时忽略。
   */
